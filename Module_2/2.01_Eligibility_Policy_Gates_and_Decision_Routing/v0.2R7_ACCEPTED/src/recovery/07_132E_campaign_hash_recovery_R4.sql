ALTER TABLE _m2_1_r4_campaign_hash_recovery
    ADD COLUMN final_campaign_row_hash text,
    ADD COLUMN final_campaign_set_hash text,
    ADD COLUMN final_registry_row_hash text,
    ADD COLUMN final_contract_set_hash text,
    ADD COLUMN final_combined_set_hash text,
    ADD COLUMN final_run_status text,
    ADD COLUMN final_contract_status text,
    ADD COLUMN final_campaign_hash_mismatches bigint,
    ADD COLUMN final_registry_hash_mismatches bigint,
    ADD COLUMN generation_evidence_hash_mismatches bigint,
    ADD COLUMN remaining_positive_evidence_rows bigint,
    ADD COLUMN preserved_history_rows bigint,
    ADD COLUMN recovery_status text;

UPDATE _m2_1_r4_campaign_hash_recovery AS recovery
SET
    final_campaign_row_hash =
    (
        SELECT c.row_hash
        FROM msbf_m2.strategy_campaign AS c
        WHERE c.module1_run_id = recovery.run_id
    ),
    final_campaign_set_hash =
    (
        SELECT r.campaign_set_hash
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = recovery.run_id
    ),
    final_registry_row_hash =
    (
        SELECT r.row_hash
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = recovery.run_id
    ),
    final_contract_set_hash =
    (
        SELECT r.contract_set_hash
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = recovery.run_id
    ),
    final_combined_set_hash =
    (
        SELECT r.combined_set_hash
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = recovery.run_id
    ),
    final_run_status =
    (
        SELECT r.run_status
        FROM msbf_ctl.run_registry AS r
        WHERE r.run_id = recovery.run_id
    ),
    final_contract_status =
    (
        SELECT r.contract_status
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = recovery.run_id
    ),
    final_campaign_hash_mismatches =
    (
        SELECT count(*)
        FROM msbf_m2.strategy_campaign AS c
        WHERE c.module1_run_id = recovery.run_id
          AND c.row_hash IS DISTINCT FROM
              msbf_ctl.m2_1_hash_jsonb(
                  to_jsonb(c) - 'row_hash' - 'created_at'
              )
    ),
    final_registry_hash_mismatches =
    (
        SELECT count(*)
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = recovery.run_id
          AND
          (
              r.row_hash IS DISTINCT FROM
                  msbf_ctl.m2_1_hash_jsonb(
                      to_jsonb(r)
                      - 'registry_id'
                      - 'contract_status'
                      - 'generated_at'
                      - 'validated_at'
                      - 'accepted_at'
                      - 'row_hash'
                      - 'created_at'
                      - 'contract_set_hash'
                      - 'combined_set_hash'
                  )
              OR r.contract_set_hash IS DISTINCT FROM md5(r.row_hash)
              OR r.campaign_set_hash IS DISTINCT FROM
                 (
                     SELECT md5(
                         string_agg(
                             c.row_hash,
                             '|' ORDER BY
                                 c.strategy_campaign_code,
                                 c.strategy_campaign_version
                         )
                     )
                     FROM msbf_m2.strategy_campaign AS c
                     WHERE c.module1_run_id = r.module1_run_id
                 )
              OR r.combined_set_hash IS DISTINCT FROM
                 (SELECT combined_set_hash FROM _m2_1_r4_combined_hash)
          )
    ),
    generation_evidence_hash_mismatches =
    (
        SELECT count(*)
        FROM msbf_ctl.run_evidence AS evidence
        CROSS JOIN msbf_ctl.m2_1_strategy_contract_registry AS registry
        WHERE evidence.run_id = recovery.run_id
          AND registry.module1_run_id = recovery.run_id
          AND
          (
              (
                  evidence.evidence_code = 'M2_1_CAMPAIGN_SET_HASH'
                  AND evidence.metric_value_text IS DISTINCT FROM
                      registry.campaign_set_hash
              )
              OR
              (
                  evidence.evidence_code = 'M2_1_COMBINED_SET_HASH'
                  AND evidence.metric_value_text IS DISTINCT FROM
                      registry.combined_set_hash
              )
          )
    ),
    remaining_positive_evidence_rows =
    (
        SELECT count(*)
        FROM msbf_ctl.run_evidence
        WHERE run_id = recovery.run_id
          AND evidence_code LIKE 'M2_1_POS_%'
    ),
    preserved_history_rows =
    (
        SELECT count(*)
        FROM msbf_ctl.run_evidence
        WHERE run_id = recovery.run_id
          AND evidence_code = 'M2_1_HIST_POS_023_V0_2R3'
    ),
    recovery_status = 'PASS'
WHERE recovery.run_id IS NOT NULL;

DO $m2_1_r4_final_guard$
DECLARE
    v record;
BEGIN
    SELECT *
    INTO v
    FROM _m2_1_r4_campaign_hash_recovery;

    IF v.final_campaign_row_hash IS DISTINCT FROM
            v.physical_campaign_row_hash
       OR v.final_campaign_set_hash IS NULL
       OR v.final_registry_row_hash IS NULL
       OR v.final_contract_set_hash IS DISTINCT FROM
            md5(v.final_registry_row_hash)
       OR v.final_combined_set_hash IS NULL
       OR v.final_run_status <> 'M2_1_GENERATED'
       OR v.final_contract_status <> 'GENERATED'
       OR v.final_campaign_hash_mismatches <> 0
       OR v.final_registry_hash_mismatches <> 0
       OR v.generation_evidence_hash_mismatches <> 0
       OR v.remaining_positive_evidence_rows <> 0
       OR v.preserved_history_rows <> 1 THEN
        RAISE EXCEPTION
            'M2.1 v0.2R4 final campaign-hash recovery state failed: %',
            row_to_json(v);
    END IF;
END;
$m2_1_r4_final_guard$;

COMMIT;

