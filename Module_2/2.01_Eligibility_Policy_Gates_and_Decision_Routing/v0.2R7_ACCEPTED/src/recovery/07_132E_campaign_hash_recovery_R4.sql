/* ============================================================================
Merchant Sales-Based Financing Strategy Simulator
M2.1 — Eligibility, Policy Gates & Decision-Routing Foundations

Program
132E_msbf_m2_1_failed_campaign_physical_row_hash_recovery_v0_2R4.sql

Purpose
Repair the sole failed positive control:

    M2_1_POS_023_CAMPAIGN_HASH

The original campaign row hash was created from a seed record whose run key
was named `run_id`. The persisted physical table names the same field
`module1_run_id`. Because the JSON key name is part of the deterministic hash,
the stored seed hash does not reconstruct from the physical campaign row.

This program:
- verifies that POS023 is the only failed positive control;
- proves the stored campaign hash equals the original seed-alias hash;
- replaces it with the physical-row hash;
- recalculates every dependent campaign, registry, contract and combined hash;
- updates the two affected generation-evidence hash values;
- preserves the failed POS023 finding as superseded audit history;
- removes stale positive-validation evidence;
- returns the run and contract to GENERATED for full revalidation.

Does not
- regenerate gate results, routing snapshots, latest, archive or comparison;
- change any policy gate, route, reason code or business outcome;
- change accepted M1.15, M1.16, M1.17 or G2 data;
- change any expected count or acceptance threshold.

Normal next
135 v0.2R4 → 136 v0.2R4 → 137 v0.2R4 → 138 v0.2R4 → 139 v0.2R4
============================================================================ */

