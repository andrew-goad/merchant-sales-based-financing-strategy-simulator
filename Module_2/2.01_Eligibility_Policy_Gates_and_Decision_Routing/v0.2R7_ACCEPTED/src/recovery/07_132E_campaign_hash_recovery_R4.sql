        FROM msbf_m2.application_eligibility_routing_latest AS l
        WHERE l.module1_run_id = (SELECT run_id FROM governed_run)

        UNION ALL

        SELECT
            'ARCHIVE',
            a.scenario_id::text || '|' || a.merchant_application_id,
            a.archive_row_hash
        FROM msbf_m2.application_eligibility_routing_archive AS a
        WHERE a.module1_run_id = (SELECT run_id FROM governed_run)

        UNION ALL

        SELECT
            'REGISTRY',
            r.contract_code || '|v' || r.contract_version::text,
            r.row_hash
        FROM msbf_ctl.m2_1_strategy_contract_registry AS r
        WHERE r.module1_run_id = (SELECT run_id FROM governed_run)
    ) AS canonical
)
SELECT
    governed_run.run_id,
    governed_run.run_status AS prior_run_status,
    contract_registry.contract_status AS prior_contract_status,

    positive_evidence.positive_checks,
    positive_evidence.positive_passes,
    positive_evidence.positive_failures,
    positive_evidence.failed_positive_codes,
    positive_evidence.reported_pos023_value,

    campaign.strategy_campaign_code,
    campaign.strategy_campaign_version,
    campaign.stored_campaign_row_hash,
    campaign.original_seed_alias_hash,
    campaign.physical_campaign_row_hash,

    contract_registry.campaign_set_hash AS prior_campaign_set_hash,
    contract_registry.registry_row_hash AS prior_registry_row_hash,
    contract_registry.reconstructed_registry_row_hash
        AS prior_reconstructed_registry_row_hash,
    contract_registry.contract_set_hash AS prior_contract_set_hash,
    contract_registry.combined_set_hash AS prior_combined_set_hash,
    current_combined.reconstructed_combined_set_hash
        AS prior_reconstructed_combined_set_hash,

    physical_counts.*,
    other_physical_hashes.*
FROM governed_run
CROSS JOIN campaign
CROSS JOIN contract_registry
CROSS JOIN positive_evidence
CROSS JOIN physical_counts
CROSS JOIN other_physical_hashes
CROSS JOIN current_combined;

DO $m2_1_r4_precondition_guard$
DECLARE
    v record;
BEGIN
    SELECT *
    INTO v
    FROM _m2_1_r4_campaign_hash_recovery;

    IF v.prior_run_status <> 'M2_1_FAILED'
       OR v.prior_contract_status <> 'GENERATED'
       OR v.positive_checks <> 112
       OR v.positive_passes <> 111
       OR v.positive_failures <> 1
       OR v.failed_positive_codes <>
            'M2_1_POS_023_CAMPAIGN_HASH'
       OR v.reported_pos023_value <> '1'
       OR v.campaign_rows <> 1
       OR v.gate_definition_rows <> 12
       OR v.reason_code_rows <> 23
       OR v.outcome_definition_rows <> 4
       OR v.gate_result_rows <> 18000
       OR v.routing_snapshot_rows <> 1500
       OR v.latest_rows <> 1500
       OR v.archive_rows <> 1500
       OR v.comparison_rows <> 750
       OR v.negative_evidence_rows <> 0
       OR v.acceptance_rows <> 0
       OR v.blocking_errors <> 0
       OR v.stored_campaign_row_hash IS DISTINCT FROM
            v.original_seed_alias_hash
       OR v.stored_campaign_row_hash IS NOT DISTINCT FROM
            v.physical_campaign_row_hash
       OR v.prior_campaign_set_hash IS DISTINCT FROM
            md5(v.stored_campaign_row_hash)
       OR v.prior_registry_row_hash IS DISTINCT FROM
            v.prior_reconstructed_registry_row_hash
       OR v.prior_contract_set_hash IS DISTINCT FROM
            md5(v.prior_registry_row_hash)
       OR v.prior_combined_set_hash IS DISTINCT FROM
            v.prior_reconstructed_combined_set_hash
       OR v.gate_definition_hash_mismatches <> 0
       OR v.reason_hash_mismatches <> 0
       OR v.outcome_hash_mismatches <> 0
       OR v.gate_result_hash_mismatches <> 0
       OR v.snapshot_hash_mismatches <> 0
       OR v.latest_hash_mismatches <> 0
       OR v.archive_hash_mismatches <> 0 THEN
        RAISE EXCEPTION
            'M2.1 v0.2R4 campaign-hash recovery preconditions failed: %',
            row_to_json(v);
    END IF;
END;
$m2_1_r4_precondition_guard$;

/* Preserve the original finding before resetting positive-validation evidence. */
INSERT INTO msbf_ctl.run_evidence
(
    run_id,
    evidence_code,
    segment_key,
    metric_name,
    metric_value_numeric,
    metric_value_text,
    unit_code,
    status,
    interpretation
)
SELECT
    run_id,
    'M2_1_HIST_POS_023_V0_2R3',
    'PORTFOLIO',
    'SUPERSEDED_CAMPAIGN_PHYSICAL_ROW_HASH_FINDING',
    NULL::numeric(24,10),
    reported_pos023_value,
    'AUDIT_HISTORY',
    'SUPERSEDED',
    'Program 135 v0.2R3 correctly identified one campaign physical-row-hash '
    || 'mismatch. The stored hash used seed key run_id; the physical table '
    || 'uses module1_run_id. v0.2R4 repairs the campaign hash and all '
    || 'dependent registry, contract, combined and generation-evidence hashes.'
FROM _m2_1_r4_campaign_hash_recovery
ON CONFLICT (run_id, evidence_code, segment_key)
DO UPDATE
SET
    metric_name = EXCLUDED.metric_name,
    metric_value_numeric = NULL,
    metric_value_text = EXCLUDED.metric_value_text,
    unit_code = EXCLUDED.unit_code,
    status = EXCLUDED.status,
    interpretation = EXCLUDED.interpretation,
    created_at = clock_timestamp();

/* Repair the physical campaign identity. */
UPDATE msbf_m2.strategy_campaign AS c
SET row_hash = r.physical_campaign_row_hash
FROM _m2_1_r4_campaign_hash_recovery AS r
WHERE c.module1_run_id = r.run_id
  AND c.strategy_campaign_code = r.strategy_campaign_code
  AND c.strategy_campaign_version = r.strategy_campaign_version
  AND c.row_hash = r.stored_campaign_row_hash;

/* Recalculate the dependent campaign-set hash first. */
UPDATE msbf_ctl.m2_1_strategy_contract_registry AS registry
SET campaign_set_hash =
(
    SELECT md5(
        string_agg(
            c.row_hash,
            '|' ORDER BY
                c.strategy_campaign_code,
                c.strategy_campaign_version
        )
    )
    FROM msbf_m2.strategy_campaign AS c
    WHERE c.module1_run_id = registry.module1_run_id
)
WHERE registry.module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery);

/* Recalculate the registry physical identity after campaign_set_hash persists. */
UPDATE msbf_ctl.m2_1_strategy_contract_registry AS registry
SET row_hash = msbf_ctl.m2_1_hash_jsonb(
    to_jsonb(registry)
    - 'registry_id'
    - 'contract_status'
    - 'generated_at'
    - 'validated_at'
    - 'accepted_at'
    - 'row_hash'
    - 'created_at'
    - 'contract_set_hash'
    - 'combined_set_hash'
)
WHERE registry.module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery);

/* Contract set is the MD5 of the immutable registry row identity. */
UPDATE msbf_ctl.m2_1_strategy_contract_registry AS registry
SET contract_set_hash = md5(registry.row_hash)
WHERE registry.module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery);

/* Reconstruct the complete 22,541-entity combined canonical hash. */
DROP TABLE IF EXISTS _m2_1_r4_combined_hash;

CREATE TEMP TABLE _m2_1_r4_combined_hash
ON COMMIT DROP
AS
SELECT
    md5(
        string_agg(
            entity_type || '|' || entity_key || '|' || row_hash,
            '|' ORDER BY entity_type, entity_key
        )
    ) AS combined_set_hash
FROM
(
    SELECT
        'CAMPAIGN'::text AS entity_type,
        c.strategy_campaign_code || '|v' ||
            c.strategy_campaign_version::text AS entity_key,
        c.row_hash
    FROM msbf_m2.strategy_campaign AS c
    WHERE c.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'GATE_DEFINITION',
        d.gate_code,
        d.row_hash
    FROM msbf_m2.policy_gate_definition AS d
    WHERE d.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'REASON_CODE',
        d.reason_code,
        d.row_hash
    FROM msbf_m2.reason_code_definition AS d
    WHERE d.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'OUTCOME',
        d.route_code,
        d.row_hash
    FROM msbf_m2.routing_outcome_definition AS d
    WHERE d.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'GATE_RESULT',
        g.scenario_id::text || '|' ||
            g.merchant_application_id || '|' || g.gate_code,
        g.row_hash
    FROM msbf_m2.application_policy_gate_result AS g
    WHERE g.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'ROUTING_SNAPSHOT',
        s.scenario_id::text || '|' || s.merchant_application_id,
        s.row_hash
    FROM msbf_m2.application_eligibility_routing_snapshot AS s
    WHERE s.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'LATEST',
        l.scenario_id::text || '|' || l.merchant_application_id,
        l.contract_row_hash
    FROM msbf_m2.application_eligibility_routing_latest AS l
    WHERE l.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'ARCHIVE',
        a.scenario_id::text || '|' || a.merchant_application_id,
        a.archive_row_hash
    FROM msbf_m2.application_eligibility_routing_archive AS a
    WHERE a.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)

    UNION ALL

    SELECT
        'REGISTRY',
        registry.contract_code || '|v' ||
            registry.contract_version::text,
        registry.row_hash
    FROM msbf_ctl.m2_1_strategy_contract_registry AS registry
    WHERE registry.module1_run_id =
          (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)
) AS canonical;

UPDATE msbf_ctl.m2_1_strategy_contract_registry AS registry
SET combined_set_hash =
    (SELECT combined_set_hash FROM _m2_1_r4_combined_hash)
WHERE registry.module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery);

/* Synchronize only the two affected generation-evidence hash values. */
UPDATE msbf_ctl.run_evidence AS evidence
SET
    metric_value_numeric = NULL,
    metric_value_text = registry.campaign_set_hash,
    interpretation =
        'Campaign set hash after v0.2R4 physical-row-hash remediation.'
FROM msbf_ctl.m2_1_strategy_contract_registry AS registry
WHERE evidence.run_id = registry.module1_run_id
  AND registry.module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)
  AND evidence.evidence_code = 'M2_1_CAMPAIGN_SET_HASH'
  AND evidence.segment_key = 'PORTFOLIO';

UPDATE msbf_ctl.run_evidence AS evidence
SET
    metric_value_numeric = NULL,
    metric_value_text = registry.combined_set_hash,
    interpretation =
        'Complete M2.1 combined canonical hash after v0.2R4 '
        || 'campaign physical-row-hash remediation.'
FROM msbf_ctl.m2_1_strategy_contract_registry AS registry
WHERE evidence.run_id = registry.module1_run_id
  AND registry.module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)
  AND evidence.evidence_code = 'M2_1_COMBINED_SET_HASH'
  AND evidence.segment_key = 'PORTFOLIO';

/* Remove stale positive evidence and return to the generated boundary. */
DELETE FROM msbf_ctl.run_evidence
WHERE run_id = (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery)
  AND evidence_code LIKE 'M2_1_POS_%';

UPDATE msbf_ctl.m2_1_strategy_contract_registry
SET
    contract_status = 'GENERATED',
    validated_at = NULL
WHERE module1_run_id =
      (SELECT run_id FROM _m2_1_r4_campaign_hash_recovery);

UPDATE msbf_ctl.run_registry
