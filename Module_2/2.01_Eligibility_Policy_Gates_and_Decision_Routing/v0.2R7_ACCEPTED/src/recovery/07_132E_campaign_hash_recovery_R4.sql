        UNION ALL

        SELECT
            'OUTCOME',
            d.route_code,
            d.row_hash
        FROM msbf_m2.routing_outcome_definition AS d
        WHERE d.module1_run_id = (SELECT run_id FROM governed_run)

        UNION ALL

        SELECT
            'GATE_RESULT',
            g.scenario_id::text || '|' ||
                g.merchant_application_id || '|' || g.gate_code,
